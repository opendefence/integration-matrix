"""Write manifests/operator/rbac.yaml and deployment.yaml from the application"""

from pathlib import Path
from typing import Any

import yaml

from . import __version__
from .app import HEALTH_PORT, app

DIRECTORY = Path(__file__).parents[2] / "manifests/operator"
IMAGE = f"ghcr.io/opendefence/integration-matrix-operator:{__version__.replace('+', '-')}"


def _dump(documents: list[dict[str, Any]]) -> str:
    header = "# Generated by `python -m opendefence_integration_matrix.render`; do not edit.\n"
    return header + yaml.safe_dump_all(documents, sort_keys=False)


def render() -> dict[str, str]:
    """Return the content of each generated file by its name."""
    # Core owns the CRDs
    documents = [document for document in app.manifests(image=IMAGE) if document["kind"] != "CustomResourceDefinition"]
    deployment = next(document for document in documents if document["kind"] == "Deployment")
    pod = deployment["spec"]["template"]["spec"]
    pod["securityContext"] = {
        "runAsNonRoot": True,
        "runAsUser": 65532,
        "runAsGroup": 65532,
        "seccompProfile": {"type": "RuntimeDefault"},
    }
    pod["volumes"] = [{"name": "tmp", "emptyDir": {}}]
    container = pod["containers"][0]
    container["env"] += [
        {"name": name, "valueFrom": {"secretKeyRef": {"name": "matrix-operator-mas", "key": key}}}
        for name, key in (("MAS_ADMIN_CLIENT_ID", "client-id"), ("MAS_ADMIN_CLIENT_SECRET", "client-secret"))
    ]
    container.update(
        ports=[{"name": "health", "containerPort": HEALTH_PORT}],
        livenessProbe={"httpGet": {"path": "/healthz", "port": "health"}},
        resources={"requests": {"cpu": "50m", "memory": "128Mi"}, "limits": {"memory": "512Mi"}},
        securityContext={
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": True,
            "capabilities": {"drop": ["ALL"]},
        },
        # The root filesystem is read-only, but cloudcoil needs a temporary directory
        volumeMounts=[{"name": "tmp", "mountPath": "/tmp"}],  # nosec B108
    )
    return {
        "rbac.yaml": _dump([document for document in documents if document is not deployment]),
        "deployment.yaml": _dump([deployment]),
    }


if __name__ == "__main__":
    for name, content in render().items():
        (DIRECTORY / name).write_text(content)
